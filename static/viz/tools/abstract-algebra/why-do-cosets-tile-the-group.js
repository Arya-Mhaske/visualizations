import { createTool } from '../../lib/tool.js';
import { dot, label, poly } from '../../lib/draw.js';
import { gcd, mod } from './_aa-math.js';
import { specFill } from './_aa-view.js';

// In ℤₙ with H = ⟨h⟩: the coset g + H is H slid round the clock by g. Slide it everywhere and the copies tile the clock.
const state = { n: 12, h: 4, g: 1, all: true };
const size = (s) => s.n / gcd(mod(s.h, s.n) || s.n, s.n);
const step = (s) => gcd(mod(s.h, s.n) || s.n, s.n);
const coset = (s, g) => { const out = []; for (let j = 0; j < size(s); j++) out.push(mod(g + j * step(s), s.n)); return out.sort((a, b) => a - b); };
const cosetIndex = (s, x) => mod(x, step(s));

createTool({
  state,
  label: 'A clock with n marks. The subgroup H is a regular polygon of marks. Sliding it round by g gives the coset g plus H. With all cosets shown, each mark has exactly one colour and every colour group has the same number of marks.',
  draw(ctx, stage, c) {
    const [cx, cy, R] = [stage.w / 2, stage.h / 2, Math.min(stage.w, stage.h) * 0.38];
    const at = (j) => [cx + R * Math.cos(-Math.PI / 2 + (2 * Math.PI * j) / state.n), cy + R * Math.sin(-Math.PI / 2 + (2 * Math.PI * j) / state.n)];
    const mine = coset(state, state.g);
    if (mine.length > 1) poly(ctx, mine.map(at), { fill: c.fillY, stroke: c.ink, width: 3 });
    for (let j = 0; j < state.n; j++) {
      const [x, y] = at(j);
      const inMine = mine.includes(j);
      dot(ctx, x, y, state.n > 16 ? 10 : 13, inMine ? c.a : state.all ? specFill(c, cosetIndex(state, j)) : c.paper, c.ink, inMine ? 3.5 : 2);
      label(ctx, String(j), x, y, c, { size: state.n > 16 ? 9 : 12, patch: false });
    }
    label(ctx, `${state.g % state.n} + H`, cx, cy, c, { size: 13 });
  },
  controls: [
    { title: 'Slide the subgroup' },
    { key: 'n', label: 'Marks on the clock, n', min: 4, max: 24, step: 1 },
    { key: 'h', label: 'H is generated by h', min: 1, max: 24, step: 1, format: (v) => String(mod(v, state.n) || state.n) },
    { key: 'g', label: 'Slide by g', min: 0, max: 23, step: 1, format: (v) => String(v % state.n) },
    { key: 'all', label: 'Colour every coset', toggle: true },
    { readout: [
      ['H has', (s) => `${size(s)} elements`],
      ['Elements of g + H', (s) => coset(s, s.g).join(', ')],
      ['Cosets in all', (s) => String(step(s))],
      ['Check', (s) => `${size(s)} × ${step(s)} = ${size(s) * step(s)} = n`],
    ] },
  ],
  tex: (s) => `|G|=|H|\\cdot[G:H]:\\quad ${s.n}=${size(s)}\\cdot ${step(s)}`,
});
