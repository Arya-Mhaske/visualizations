import { createTool } from '../../lib/tool.js';
import { label } from '../../lib/draw.js';
import { alternatingGroup, derivedSeries, symmetricGroup } from './_aa-math.js';

// Galois: a polynomial can be solved with roots (radicals) only if its Galois group is solvable, meaning that repeatedly
// taking commutator subgroups [G, G] reaches the trivial group. The tool computes that chain of subgroups by brute force.
const GROUPS = {
  s2: { name: 'S₂', make: () => symmetricGroup(2), example: 'x² − 2' },
  s3: { name: 'S₃', make: () => symmetricGroup(3), example: 'x³ − 2' },
  s4: { name: 'S₄', make: () => symmetricGroup(4), example: 'x⁴ − x − 1' },
  a5: { name: 'A₅', make: () => alternatingGroup(5), example: 'no formula is needed here' },
  s5: { name: 'S₅', make: () => symmetricGroup(5), example: 'x⁵ − 6x + 3' },
};
const state = { group: 's4' };
const cache = {};
const seriesOf = (key) => (cache[key] ||= derivedSeries(GROUPS[key].make()));
const solvable = (key) => seriesOf(key).at(-1) === 1;
const NAMES = { 1: '{e}', 2: 'S₂', 3: 'A₃', 4: 'V₄', 6: 'S₃', 12: 'A₄', 24: 'S₄', 60: 'A₅', 120: 'S₅' };

createTool({
  state,
  label: 'A ladder of boxes. The top box is the group. Each box below is its commutator subgroup, the subgroup generated by all products a b a-inverse b-inverse. If the ladder reaches the trivial group at the bottom, the group is solvable and equations with it can be solved by radicals. For A5 and S5 the ladder gets stuck.',
  draw(ctx, stage, c) {
    const sizes = seriesOf(state.group);
    const levels = [...sizes];
    const stuck = !solvable(state.group);
    if (stuck) levels.pop();
    const h = Math.min(54, (stage.h - 40) / (levels.length + (stuck ? 1 : 0)) - 8);
    const wMax = stage.w - 40;
    const rows = levels.map((n) => ({ text: `${NAMES[n] || n}   (${n} elements)`, size: n }));
    if (stuck) rows.push({ text: 'the same group again: the ladder is stuck', size: 0 });
    rows.forEach((row, i) => {
      const y = 18 + i * (h + 8);
      const w = row.size ? Math.max(wMax * (Math.log(row.size + 1) / Math.log(121)), 70) : wMax;
      const x = (stage.w - w) / 2;
      ctx.fillStyle = row.size === 0 ? c.fillA : row.size === 1 ? c.fillC : i === 0 ? c.fillY : c.fillB;
      ctx.fillRect(x, y, w, h);
      ctx.strokeStyle = c.ink;
      ctx.lineWidth = 3;
      ctx.strokeRect(x, y, w, h);
      label(ctx, row.text, stage.w / 2, y + h / 2, c, { size: 12, patch: false, bounds: stage });
      if (i < rows.length - 1) label(ctx, '↓ [G, G]', stage.w / 2 + wMax * 0.3, y + h + 4, c, { size: 10, patch: false });
    });
  },
  controls: [
    { title: 'Pick a Galois group' },
    { key: 'group', label: 'Group', options: Object.entries(GROUPS).map(([k, v]) => [k, v.name]) },
    { readout: [
      ['Sizes down the ladder', (s) => seriesOf(s.group).join(' → ')],
      ['Reaches {e}?', (s) => ({ text: solvable(s.group) ? 'yes: solvable' : 'no: stuck', good: solvable(s.group) })],
      ['Solvable by radicals?', (s) => ({ text: solvable(s.group) ? 'yes' : 'no', good: solvable(s.group) })],
      ['Example polynomial', (s) => (s.group === 'a5' ? 'a quintic with this group exists, with no general formula' : `${GROUPS[s.group].example} has group ${GROUPS[s.group].name}`)],
    ] },
  ],
  tex: (s) => `${seriesOf(s.group).join('\\to ')}`,
});
